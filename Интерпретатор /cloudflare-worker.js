  const hrvLow      = hrvVal < hrvNormLow;
  const hrvHigh     = hrvVal > hrvNormHigh;
  const hrvStatus   = hrvLow ? 'ниже нормы для возраста' : hrvHigh ? 'выше нормы — хорошее восстановление' : 'в норме для возраста';
