-- 2026-07-24 — docs/COMPLIANCE-PROM-MASTER-PLAN.md). Этап 1: серверная часть.
--
-- Принцип: аккаунта у приложения нет вообще, поэтому здесь нет ни почты, ни имени,
-- ни кода доступа — только псевдонимный id установки (`vialp_pid`, случайный UUID,
-- живёт на устройстве) и обезличенные метрики дня. Свободных текстов таблица не
-- принимает: жалоба своими словами, заметки о событиях и новые симптомы остаются
-- на устройстве, их сюда не пускает whitelist в воркере (handleResearchDay).
--
-- Право на удаление (GDPR ст. 17, WA MHMDA): POST /research/forget с тем же pid
-- стирает все строки установки. Никакой связи pid↔человек у нас нет, поэтому
-- удаление возможно только с самого устройства.
--
-- Применить: wrangler d1 execute vial-cabinet --remote --file=research-schema.sql
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS research_days (
  pid          TEXT    NOT NULL,           -- псевдонимный id установки (vialp_pid)
  day          TEXT    NOT NULL,           -- YYYY-MM-DD, день записи
  ts           INTEGER,                    -- время записи на устройстве
  received_ts  INTEGER NOT NULL,           -- когда строка пришла на сервер
  sv           INTEGER,                    -- версия схемы записи
  wv           INTEGER,                    -- версия весов индекса
  src          TEXT,                       -- источник данных дня: гаджет / ручной ввод
  lang         TEXT,                       -- язык интерфейса (для стратификации выборки)
  data         TEXT    NOT NULL,           -- JSON только из whitelist-полей (см. воркер)
  PRIMARY KEY (pid, day)                   -- один день = одна строка; правка дня перезаписывает
);

-- Выборки для будущего анализа идут по дню и по версии схемы: индексы под них.
CREATE INDEX IF NOT EXISTS idx_research_day ON research_days(day);
CREATE INDEX IF NOT EXISTS idx_research_sv  ON research_days(sv, wv);
