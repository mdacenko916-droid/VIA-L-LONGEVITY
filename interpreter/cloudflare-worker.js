// POST /draft  → принимает данные Expert-запроса от Apps Script, сохраняет
// черновик в KV, генерирует AI-bullet-points и отправляет нутрициологу
// карточку клиента с inline-кнопками.
async function handleDraft(request, env, corsHeaders) {
  if (!env.TELEGRAM_BOT_TOKEN || !env.NUTRITIONIST_CHAT_ID) {
    return jsonResponse({ ok: false, error: 'tg_secrets_missing' }, corsHeaders, 500);
  }
  if (!env.EXPERT_DRAFTS) {
    return jsonResponse({ ok: false, error: 'kv_binding_missing' }, corsHeaders, 500);
  }
  let payload = {};
  try { payload = await request.json(); }
  catch (e) { return jsonResponse({ ok: false, error: 'invalid_json' }, corsHeaders, 400); }

  // AI-ассистент: 5–7 наблюдений для нутрициолога. Fail-safe — если Claude
  // упал, карточка всё равно отправится, просто без AI-блока.
  let aiBullets = '';
  try {
    aiBullets = await generateAiBullets(env, payload);
  } catch (e) {
    console.error('generateAiBullets failed:', e?.message || e);
  }

  // Сохраняем черновик в KV под уникальным request_id (TTL 7 дней).
  const requestId = crypto.randomUUID();
  await env.EXPERT_DRAFTS.put('draft:' + requestId, JSON.stringify({
    ...payload,
    ai_bullets: aiBullets,
    status: 'pending',
    nutritionist_reply: null,
    created_at: new Date().toISOString()
  }), { expirationTtl: 7 * 24 * 60 * 60 });

  const tg = await sendTelegram(
    env,
    renderDraftCard(payload, aiBullets),
    { reply_markup: buildDraftKeyboard(requestId) }
  );
  return jsonResponse({ ok: true, request_id: requestId, ai_used: !!aiBullets, tg }, corsHeaders);
}

// AI-ассистент: на основе биометрии/симптомов/паттернов KB просит Claude
// дать 5–7 коротких bullet-points нутрициологу. НЕ финальный разбор —
// только подсказки «на что обратить внимание».
async function generateAiBullets(env, payload) {
  if (!env.CLAUDE_API_KEY) return '';
  const d = payload.data || {};

  const bio = [];
  if (d.hrv)        bio.push(`HRV ${d.hrv}мс`);
  if (d.rhr)        bio.push(`ЧСС покоя ${d.rhr}`);
  if (d.sleep_qual) bio.push(`качество сна ${d.sleep_qual}/10`);
  if (d.deep)       bio.push(`глубокий сон ${d.deep}`);
  if (d.wake)       bio.push(`пробуждения ${d.wake}`);
  if (d.energy)     bio.push(`энергия ${d.energy}/10`);
  if (d.anxiety)    bio.push(`тревога ${d.anxiety}/10`);
  if (d.temp)       bio.push(`ночн. температура ${d.temp}`);
  if (d.resp_rate)  bio.push(`ЧД ${d.resp_rate}`);

  const symptoms     = Array.isArray(d.symptoms)      ? d.symptoms.join(', ')      : '';
  const hormSymptoms = Array.isArray(d.horm_symptoms) ? d.horm_symptoms.join(', ') : '';
  const hotflashes   = [d.hf_count, d.hf_intensity, d.hf_time].filter(Boolean).join(' · ');

  let patterns = '';
  try {
    const ids = selectKBPatterns(d) || [];
    patterns = ids.length ? ids.join(', ') : '';
  } catch (e) { /* selectKBPatterns может бросить — игнорируем */ }

  const ctx = [];
  ctx.push(`Профиль: ${d.gender === 'male' ? 'мужчина' : 'женщина'}, ${d.age || '?'} лет, фаза «${d.phase || '?'}»`);
  if (d.device)       ctx.push(`Источник данных (трекер): ${d.device}`);
  if (bio.length)     ctx.push(`Биометрия: ${bio.join(', ')}`);
  if (symptoms)       ctx.push(`Симптомы: ${symptoms}`);
  if (hormSymptoms)   ctx.push(`Гормональные симптомы: ${hormSymptoms}`);
  if (hotflashes)     ctx.push(`Приливы: ${hotflashes}`);
  if (d.cycle_status) ctx.push(`Цикл: ${d.cycle_status}`);
  if (payload.question) ctx.push(`Вопрос клиента: ${payload.question}`);
  if (patterns)       ctx.push(`Активные KB-паттерны: ${patterns}`);

  const prompt =
    'Ты ассистент-аналитик нутрициолога VIA-L. Изучи данные клиента и выдай СТРОГО 5–7 коротких bullet-points: ' +
    'что заметил в данных и на что нутрициологу обратить внимание при подготовке разбора. ' +
    'Без вступления, без заключения — только список. Каждая строка начинается с маркера «• ». ' +
    'Профессионально, конкретно, без воды. Ответ ТОЛЬКО на русском (нутрициолог работает на русском). ' +
    'НЕ используй Markdown — никаких **, __, ~~, ` — пиши обычным текстом, для акцентов можно ВЕРХНИЙ регистр. ' +
    'Не вставляй пустые строки между пунктами — каждая строка это отдельный bullet.\n\n' +
    'Данные клиента:\n' + ctx.join('\n');

  const response = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': env.CLAUDE_API_KEY,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model: 'claude-haiku-4-5-20251001',
      max_tokens: 600,
      messages: [{ role: 'user', content: prompt }],
    }),
  });

  if (!response.ok) return '';
  const result = await response.json();
  return (result.content?.[0]?.text || '').trim();
}

// Рендер карточки клиента из payload draft (+ опционально AI-bullet-points).
function renderDraftCard(payload, aiBullets) {
  const d = payload.data || {};
  const lines = [];
  lines.push('📋 <b>Новый Expert-разбор</b>');
  lines.push(`<b>Тариф:</b> ${esc(payload.plan)}${payload.week_no ? ` · неделя ${esc(payload.week_no)}` : ''}`);
  lines.push(`<b>Клиент:</b> ${esc(payload.client_name) || '—'} · ${esc(payload.client_email) || '—'}`);
  lines.push(`<b>Код:</b> <code>${esc(payload.code)}</code> · <b>язык:</b> ${esc(payload.lang || 'en')}`);
  lines.push('');
  lines.push(`<b>Профиль:</b> ${d.gender === 'male' ? 'М' : 'Ж'} · фаза ${esc(d.phase) || '—'}${d.age ? ' · ' + d.age + ' лет' : ''}`);
  if (d.device) lines.push(`<b>Гаджет:</b> ${esc(d.device)}`);
  const bio = [];
  if (d.hrv)        bio.push(`HRV ${d.hrv}мс`);
  if (d.rhr)        bio.push(`ЧСС ${d.rhr}`);
  if (d.sleep_qual) bio.push(`сон ${d.sleep_qual}/10`);
  if (d.energy)     bio.push(`энергия ${d.energy}/10`);
  if (d.anxiety)    bio.push(`тревога ${d.anxiety}/10`);
  if (bio.length)   lines.push(`<b>Биометрия:</b> ${bio.join(' · ')}`);
  if (Array.isArray(d.symptoms) && d.symptoms.length) {
    lines.push(`<b>Симптомы:</b> ${esc(d.symptoms.join(', '))}`);
  }
  if (payload.question) {
    lines.push('');
    lines.push('<b>Вопрос клиента:</b>');
    lines.push(esc(payload.question));
  }
  if (aiBullets) {
    lines.push('');
    lines.push('🤖 <b>AI-ассистент — обратите внимание:</b>');
    lines.push(mdBoldToHtml(aiBullets));
  }
  const onbLines = renderOnboardingBlock(payload.onboarding);
  if (onbLines.length) onbLines.forEach(l => lines.push(l));
  return lines.join('\n');
}

// Безопасное превращение оставшихся **…** в <b>…</b> для Telegram parse_mode=HTML.
// Сначала экранируем HTML-спецсимволы, потом конвертируем markdown-bold.
function mdBoldToHtml(s) {
  if (!s) return '';
  return esc(s).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
}

// mode='initial'    → две кнопки (нутрициолог обязан отредактировать перед отправкой)
// mode='after_edit' → три кнопки, включая «✅ Отправить клиенту»
function buildDraftKeyboard(requestId, mode) {
  if (mode === 'after_edit') {
    return {
      inline_keyboard: [[
        { text: '✅ Отправить клиенту', callback_data: 'approve:' + requestId },
        { text: '✏️ Переписать',         callback_data: 'edit:'    + requestId },
        { text: '❌ Отклонить',          callback_data: 'reject:'  + requestId }
      ]]
    };
  }
  return {
    inline_keyboard: [[
      { text: '✏️ Написать ответ', callback_data: 'edit:'   + requestId },
      { text: '❌ Отклонить',       callback_data: 'reject:' + requestId }
    ]]
  };
}

// POST /tg-webhook  → принимает callback_query (нажатие кнопки) или message
// (реплай при редактировании) от Telegram.
async function handleTgWebhook(request, env, corsHeaders) {
  if (!env.TELEGRAM_BOT_TOKEN || !env.NUTRITIONIST_CHAT_ID || !env.EXPERT_DRAFTS) {
    return jsonResponse({ ok: false, error: 'config_missing' }, corsHeaders, 500);
  }
  let update;
  try { update = await request.json(); }
  catch (e) { return jsonResponse({ ok: false, error: 'invalid_json' }, corsHeaders, 400); }

  if (update.callback_query) {
    return handleTgCallback(update.callback_query, env, corsHeaders);
  }
  if (update.message) {
    return handleTgMessage(update.message, env, corsHeaders);
  }
  return jsonResponse({ ok: true, skipped: 'unsupported_update' }, corsHeaders);
}

async function handleTgCallback(cq, env, corsHeaders) {
  const chatId    = cq.message?.chat?.id;
  const messageId = cq.message?.message_id;
  const cqData    = cq.data || '';
  const colonIdx  = cqData.indexOf(':');
  const action    = colonIdx >= 0 ? cqData.slice(0, colonIdx) : '';
  const requestId = colonIdx >= 0 ? cqData.slice(colonIdx + 1) : '';

  // Безопасность: реагируем только если callback пришёл от нашего нутрициолога.
  if (chatId?.toString() !== env.NUTRITIONIST_CHAT_ID?.toString()) {
    await tgAnswerCallback(env, cq.id, '');
    return jsonResponse({ ok: false, error: 'foreign_chat' }, corsHeaders);
  }
  if (!action || !requestId) {
    await tgAnswerCallback(env, cq.id, 'Неверные данные');
    return jsonResponse({ ok: false, error: 'bad_callback_data' }, corsHeaders);
  }

  // ── Scheduling button from program intake ──────────────────
  if (action === 'sched') {
    const intakeRaw = env.PROGRAM_INTAKES
      ? await env.PROGRAM_INTAKES.get('intake:' + requestId)
      : null;

    if (!intakeRaw) {
      await tgAnswerCallback(env, cq.id, 'Анкета не найдена или устарела', true);
      return jsonResponse({ ok: false, error: 'intake_not_found' }, corsHeaders);
    }

    const intake     = JSON.parse(intakeRaw);
    const clientName = intake.answers?.name || intake.name || '—';
    const calLink    = 'https://via-l.com/program-intake.html?t=' + requestId + '&calendar=1';

    await tgAnswerCallback(env, cq.id, '📅 Ссылка сформирована');
    await sendTelegramTo(env, chatId,
      `📅 <b>Ссылка на выбор времени сессии</b>\n\n`
      + `Клиент: <b>${esc(clientName)}</b>\n\n`
      + `Отправьте клиенту эту ссылку (в Telegram или email):\n`
      + `<code>${calLink}</code>`,
    );
    return jsonResponse({ ok: true }, corsHeaders);
  }

  const raw = await env.EXPERT_DRAFTS.get('draft:' + requestId);
  if (!raw) {
    await tgAnswerCallback(env, cq.id, 'Запрос устарел');
    return jsonResponse({ ok: false, error: 'draft_not_found' }, corsHeaders);
  }
  const draft = JSON.parse(raw);

  if (action === 'approve') {
    // Защита: на этом этапе у draft уже ДОЛЖЕН быть nutritionist_reply
    // (кнопка «Отправить клиенту» доступна только в режиме after_edit).
    if (!draft.nutritionist_reply) {
      await tgAnswerCallback(env, cq.id, 'Сначала напишите ответ через ✏️ Редактировать');
      return jsonResponse({ ok: false, error: 'no_reply_yet' }, corsHeaders);
    }

    // Перевод ответа на язык клиента (если он не ru/uk).
    let finalReply = draft.nutritionist_reply;
    const clientLang = (draft.lang || 'en').toLowerCase();
    if (clientLang !== 'ru' && clientLang !== 'uk') {
      try {
        finalReply = await translateReply(env, draft.nutritionist_reply, clientLang);
      } catch (e) {
        console.error('translateReply failed:', e?.message || e);
        // Fallback: отправляем оригинал на ru с пометкой.
        finalReply = '[' + clientLang.toUpperCase() + ' translation failed, original RU text below]\n\n' + draft.nutritionist_reply;
      }
    }

    // Отправка PDF клиенту через Apps Script (action=send_report).
    let sendResult = null;
    if (env.APPS_SCRIPT_URL) {
      try {
        const r = await fetch(env.APPS_SCRIPT_URL, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            action:        'send_report',
            client_name:   draft.client_name,
            client_email:  draft.client_email,
            code:          draft.code,
            lang:          clientLang,
            plan:          draft.plan,
            week_no:       draft.week_no,
            data:          draft.data,
            question:      draft.question,
            reply_text:    finalReply,
            reply_orig:    draft.nutritionist_reply,
            reply_lang:    'ru'
          }),
          redirect: 'follow'
        });
        sendResult = await r.json();
      } catch (e) {
        console.error('send_report call failed:', e?.message || e);
        await tgAnswerCallback(env, cq.id, '⚠ Ошибка отправки клиенту');
        return jsonResponse({ ok: false, error: 'apps_script_call_failed' }, corsHeaders);
      }
    } else {
      console.error('APPS_SCRIPT_URL not set in env');
    }

    draft.status      = 'approved';
    draft.approved_at = new Date().toISOString();
    draft.send_result = sendResult;

    const sentOk = sendResult && sendResult.ok;
    await tgEditMessage(env, chatId, messageId,
      (sentOk ? '✅ <b>Отправлено клиенту</b>' : '⚠ <b>Утверждено, но отправка дала сбой</b>') +
      '\n\nКлиент: <code>' + esc(draft.client_email) + '</code>' +
      '\nЯзык: ' + esc(clientLang) +
      (clientLang !== 'ru' && clientLang !== 'uk' ? ' <i>(переведено с ru)</i>' : '') +
      (sentOk ? '' : '\n\n<code>' + esc(JSON.stringify(sendResult || {error:'no_response'})) + '</code>')
    );
    await env.EXPERT_DRAFTS.delete('draft:' + requestId);
    await tgAnswerCallback(env, cq.id, sentOk ? '✅ Отправлено клиенту' : '⚠ Сбой отправки');
  }
  else if (action === 'reject') {
    draft.status = 'rejected';
    // TODO: отправить клиенту вежливое сообщение «требуется уточнение».
    await tgEditMessage(env, chatId, messageId,
      '❌ <b>Отклонено</b>\n\nКлиент: <code>' + esc(draft.client_email) + '</code>'
    );
    await env.EXPERT_DRAFTS.delete('draft:' + requestId);
    await tgAnswerCallback(env, cq.id, '❌ Отклонено');
  }
  else if (action === 'edit') {
    // Включаем режим редактирования на 10 минут.
    await env.EXPERT_DRAFTS.put('editing:' + chatId, requestId, { expirationTtl: 10 * 60 });
    await tgSendMessage(env, chatId,
      '✏️ <b>Режим редактирования</b>\n\nПришлите свой текст разбора одним сообщением. После — карточка вернётся с кнопками для подтверждения.\n\n<i>10 минут на правку.</i>'
    );
    await tgAnswerCallback(env, cq.id, 'Жду ваш текст');
  }
  else {
    await tgAnswerCallback(env, cq.id, 'Неизвестное действие');
  }

  return jsonResponse({ ok: true }, corsHeaders);
}

async function handleTgMessage(msg, env, corsHeaders) {
  const chatId = msg.chat?.id;
  const text   = msg.text;

  // Реагируем только на сообщения от нутрициолога и только когда есть активный режим редактирования.
  if (chatId?.toString() !== env.NUTRITIONIST_CHAT_ID?.toString()) {
    return jsonResponse({ ok: true, skipped: 'foreign_chat' }, corsHeaders);
  }
  if (!text) return jsonResponse({ ok: true, skipped: 'no_text' }, corsHeaders);

  const editingRequestId = await env.EXPERT_DRAFTS.get('editing:' + chatId);
  if (!editingRequestId) {
    return jsonResponse({ ok: true, skipped: 'not_editing' }, corsHeaders);
  }

  const raw = await env.EXPERT_DRAFTS.get('draft:' + editingRequestId);
  if (!raw) {
    await tgSendMessage(env, chatId, '⚠ Черновик устарел или удалён. Начните заново — пришлите новый Expert-запрос.');
    await env.EXPERT_DRAFTS.delete('editing:' + chatId);
    return jsonResponse({ ok: false, error: 'draft_expired' }, corsHeaders);
  }

  const draft = JSON.parse(raw);
  draft.nutritionist_reply = text;
  draft.edited_at = new Date().toISOString();
  await env.EXPERT_DRAFTS.put('draft:' + editingRequestId, JSON.stringify(draft), { expirationTtl: 7 * 24 * 60 * 60 });
  await env.EXPERT_DRAFTS.delete('editing:' + chatId);

  const preview = text.length > 500 ? text.slice(0, 500) + '…' : text;
  await tgSendMessage(env, chatId,
    '✏️ <b>Текст сохранён.</b>\n\n' + esc(preview) + '\n\n<i>Подтвердите отправку клиенту:</i>',
    { reply_markup: buildDraftKeyboard(editingRequestId, 'after_edit') }
  );

  return jsonResponse({ ok: true, saved: true }, corsHeaders);
}

// Перевод ответа нутрициолога (ru) на язык клиента через Claude API.
// Сохраняем структуру (абзацы, списки, переносы) и медицинскую точность.
async function translateReply(env, text, targetLang) {
  if (!env.CLAUDE_API_KEY) return text;

  const langName = {
    en: 'English', es: 'Spanish', de: 'German', pt: 'Portuguese',
    fr: 'French',  pl: 'Polish',  it: 'Italian', he: 'Hebrew',
    ja: 'Japanese', ko: 'Korean'
  }[targetLang] || targetLang;

  const prompt =
    'Translate the following message from a clinical nutritionist (originally written in Russian) into ' + langName + '. ' +
    'Preserve exact structure: paragraphs, bullet lists, line breaks, headings. ' +
    'Keep medical and supplement names accurate (use international/Latin names where appropriate). ' +
    'Tone: warm but professional, addressing the client directly. ' +
    'OUTPUT: ONLY the translated text, no preamble, no commentary, no quotes around it.\n\n' +
    'Original text:\n' + text;

  const response = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': env.CLAUDE_API_KEY,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model: 'claude-haiku-4-5-20251001',
      max_tokens: 2000,
      messages: [{ role: 'user', content: prompt }],
    }),
  });

  if (!response.ok) throw new Error('claude http ' + response.status);
  const result = await response.json();
  return (result.content?.[0]?.text || '').trim() || text;
}

